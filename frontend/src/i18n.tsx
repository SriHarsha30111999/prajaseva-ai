type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string, vars?: Record<string, string | number>) => string };
const I18nContext = createContext<Ctx>(null as unknown as Ctx);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>((localStorage.getItem("prajaseva_lang") as Lang) || "te");
  const setLang = (l: Lang) => {
    localStorage.setItem("prajaseva_lang", l);
    document.documentElement.lang = l;
    setLangState(l);
  };
  const t = (k: string, vars?: Record<string, string | number>) => {
    let s = D[k]?.[lang === "te" ? 0 : 1] ?? k;
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
    return s;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

export function fmtDate(iso: string | null | undefined, lang: Lang, withTime = false) {
  if (!iso) return "-";
  return new Date(iso).toLocaleString(lang === "te" ? "te-IN" : "en-IN", {
    day: "2-digit", month: "short", year: "numeric", ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  });
}

export const fmtMoney = (n: number) => "₹" + Math.round(n).toLocaleString("en-IN");
